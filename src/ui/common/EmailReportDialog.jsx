import React, { useState, useEffect } from 'react';
import { RightSideDialog } from './RightSideDialog';
import { useTheme } from '../Settings/themeUtils';
import { Button } from './Button';
import { Select } from './Select';
import { FiMail, FiSend, FiLoader, FiCheckCircle, FiSliders } from 'react-icons/fi';

export const EmailReportDialog = ({ visible, onHide, reportName }) => {
  const { themeUtils } = useTheme();

  const [formData, setFormData] = useState({
    subject: `CLMS: ${reportName} Statement`,
    recipients: 'management@clms-portal.in, supervisor@clms-portal.in',
    body: `Dear Team,\n\nPlease find attached the dynamic ${reportName} report generated by the CLMS System.\n\nBest regards,\nCLMS Administration`,
    format: 'PDF'
  });

  const [sendingStep, setSendingStep] = useState('form'); // 'form' | 'sending' | 'done'
  const [progress, setProgress] = useState(0);
  const [logs, setLogs] = useState([]);

  useEffect(() => {
    if (visible) {
      setFormData({
        subject: `CLMS: ${reportName} Statement`,
        recipients: 'management@clms-portal.in, supervisor@clms-portal.in',
        body: `Dear Team,\n\nPlease find attached the dynamic ${reportName} report generated by the CLMS System.\n\nBest regards,\nCLMS Administration`,
        format: 'PDF'
      });
      setSendingStep('form');
      setProgress(0);
      setLogs([]);
    }
  }, [visible, reportName]);

  const handleSend = () => {
    if (!formData.recipients) {
      alert('Please specify at least one recipient email address.');
      return;
    }

    setSendingStep('sending');
    setProgress(0);
    setLogs(['[1/5] Extracting live query filters and records...']);

    const steps = [
      '[2/5] Compiling records and formatting data cells...',
      `[3/5] Constructing attachments in ${formData.format} format...`,
      '[4/5] Establishing secure handshake with smtp.clms-system.org...',
      `[5/5] Dispatched report to: ${formData.recipients}... Sent.`,
      '✓ Email sent successfully. Delivery confirmation logged.'
    ];

    let currentStep = 0;
    const interval = setInterval(() => {
      currentStep += 1;
      const calculatedProgress = Math.min(100, Math.floor((currentStep / steps.length) * 100));
      setProgress(calculatedProgress);

      setLogs(prev => [...prev, steps[currentStep - 1]]);

      if (currentStep >= steps.length) {
        clearInterval(interval);
        setSendingStep('done');
      }
    }, 700);
  };

  return (
    <RightSideDialog
      visible={visible}
      onHide={onHide}
      header={`Email Report: ${reportName}`}
    >
      <div className="flex flex-col h-full">
        <div className="flex-1 overflow-y-auto hide-scrollbar p-6 space-y-6">

          {sendingStep === 'form' && (
            <div className="space-y-4">
              <h3 className="text-lg font-bold border-b pb-2 flex items-center gap-2" style={{ color: themeUtils.getTextColor(true), borderColor: themeUtils.getBorderColor() }}>
                <FiMail /> Dispatch Configuration
              </h3>

              <div className="space-y-4">
                <div>
                  <label className="text-sm font-medium mb-1 block" style={{ color: themeUtils.getTextColor(true) }}>Recipients <span className="text-red-500">*</span></label>
                  <input
                    type="text"
                    value={formData.recipients}
                    onChange={(e) => setFormData({ ...formData, recipients: e.target.value })}
                    placeholder="e.g. manager@site.com, admin@site.com"
                    className="w-full px-3 py-2 rounded-lg border text-sm"
                    style={{ backgroundColor: themeUtils.getBgColor('input'), borderColor: themeUtils.getBorderColor(), color: themeUtils.getTextColor(true) }}
                  />
                </div>

                <div>
                  <label className="text-sm font-medium mb-1 block" style={{ color: themeUtils.getTextColor(true) }}>Subject Line</label>
                  <input
                    type="text"
                    value={formData.subject}
                    onChange={(e) => setFormData({ ...formData, subject: e.target.value })}
                    className="w-full px-3 py-2 rounded-lg border text-sm"
                    style={{ backgroundColor: themeUtils.getBgColor('input'), borderColor: themeUtils.getBorderColor(), color: themeUtils.getTextColor(true) }}
                  />
                </div>

                <div>
                  <label className="text-sm font-medium mb-1 block" style={{ color: themeUtils.getTextColor(true) }}>Message Body</label>
                  <textarea
                    rows="5"
                    value={formData.body}
                    onChange={(e) => setFormData({ ...formData, body: e.target.value })}
                    className="w-full px-3 py-2 rounded-lg border text-sm"
                    style={{ backgroundColor: themeUtils.getBgColor('input'), borderColor: themeUtils.getBorderColor(), color: themeUtils.getTextColor(true) }}
                  ></textarea>
                </div>

                <div>
                  <label className="text-sm font-medium mb-1 block" style={{ color: themeUtils.getTextColor(true) }}>Attachment Format</label>
                  <Select
                    className="w-full"
                    value={formData.format}
                    onChange={(e) => setFormData({ ...formData, format: e.target.value })}
                    options={[
                      { label: 'PDF Document (.pdf)', value: 'PDF' },
                      { label: 'Excel Spreadsheet (.xlsx)', value: 'Excel' },
                      { label: 'CSV File (.csv)', value: 'CSV' }
                    ]}
                  />
                </div>
              </div>
            </div>
          )}

          {sendingStep === 'sending' && (
            <div className="space-y-6 min-h-screen py-6">
              <div className="text-center space-y-3">
                <FiLoader className="animate-spin mx-auto text-4xl text-indigo-600" />
                <h3 className="font-bold text-lg" style={{ color: themeUtils.getTextColor(true) }}>Sending Report Email</h3>
                <p className="text-sm" style={{ color: themeUtils.getTextColor(false) }}>Generating attachments and dispatching payload...</p>
              </div>

              {/* Progress bar */}
              <div className="w-full bg-gray-100 dark:bg-gray-800 rounded-full h-3 overflow-hidden">
                <div className="bg-indigo-600 h-3 rounded-full transition-all duration-300" style={{ width: `${progress}%` }}></div>
              </div>

              {/* Logs console */}
              <div className="bg-gray-950 text-emerald-400 font-mono p-4 rounded-xl text-xs space-y-2 border border-gray-800 h-48 overflow-y-auto">
                {logs.map((log, idx) => (
                  <div key={idx} className="leading-relaxed">{log}</div>
                ))}
              </div>
            </div>
          )}

          {sendingStep === 'done' && (
            <div className="text-center space-y-4 py-8 animate-fade-in">
              <FiCheckCircle className="mx-auto text-6xl text-emerald-500 animate-bounce" />
              <h3 className="font-bold text-2xl" style={{ color: themeUtils.getTextColor(true) }}>Report Sent Successfully</h3>
              <p className="text-sm max-w-sm mx-auto" style={{ color: themeUtils.getTextColor(false) }}>
                The {reportName} report has been compiled and emailed to the designated recipients.
              </p>
              <div className="bg-gray-950 text-emerald-400 font-mono p-4 rounded-xl text-xs space-y-2 border border-gray-800 text-left max-w-md mx-auto max-h-32 overflow-y-auto">
                {logs.slice(-2).map((log, idx) => (
                  <div key={idx}>{log}</div>
                ))}
              </div>
            </div>
          )}

        </div>

        <div className="p-4 border-t flex justify-end gap-2" style={{ backgroundColor: themeUtils.getBgColor('card'), borderColor: themeUtils.getBorderColor() }}>
          <Button variant="outline" onClick={onHide} style={{ color: themeUtils.getTextColor(true), borderColor: themeUtils.getBorderColor() }}>
            {sendingStep === 'done' ? 'Close' : 'Cancel'}
          </Button>
          {sendingStep === 'form' && (
            <Button variant="primary" onClick={handleSend}>
              <FiSend className="mr-2" /> Send Email
            </Button>
          )}
        </div>
      </div>
    </RightSideDialog>
  );
};
